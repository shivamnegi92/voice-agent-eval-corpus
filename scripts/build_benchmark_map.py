#!/usr/bin/env python3
"""Generate BENCHMARKS.md, the benchmark map, from corpus/voice_agent_corpus.csv.

Usage:
    python3 scripts/build_benchmark_map.py           # rewrite BENCHMARKS.md
    python3 scripts/build_benchmark_map.py --check   # exit 1 if BENCHMARKS.md is stale

Never edit BENCHMARKS.md by hand: change the coding, then regenerate.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "corpus" / "voice_agent_corpus.csv"
OUT = ROOT / "BENCHMARKS.md"

AXES = [("timing", "T"), ("recovery", "R"), ("grounded", "G"), ("multiparty", "M")]
CONDITIONS = [("real_speech", "RS"), ("non_english", "NE"), ("acoustic_variation", "AV"),
              ("long_session", "LS")]
INSTRUMENTS = [("state_verification", "S"), ("human_reference", "H"), ("model_judge", "J"),
               ("simulation", "Sim")]
COLUMNS = AXES + CONDITIONS + INSTRUMENTS


def split(value: str) -> set[str]:
    return {v for v in value.split(";") if v}


def short_name(title: str) -> str:
    head = re.split(r":\s", title, maxsplit=1)[0].strip()
    return head if len(head) <= 48 else head[:45].rstrip() + "..."


def published(venue: str) -> str:
    if venue.lower().startswith("arxiv"):
        return "preprint"
    venue = venue.replace("Findings of the Association for Computational Linguistics", "Findings")
    return re.sub(r"^Proceedings of (the )?", "", venue)


def table(rows: list[dict]) -> list[str]:
    header = "| Work | Year | " + " | ".join(code for _, code in COLUMNS) + " | Venue |"
    lines = [header, "|" + "---|" * (len(COLUMNS) + 3)]
    for r in rows:
        flags = split(r["capability_axes"]) | split(r["conditions"]) | split(r["instruments"])
        cells = ["x" if key in flags else "" for key, _ in COLUMNS]
        name = f"[{short_name(r['title'])}]({r['url']})".replace("|", "\\|")
        lines.append(f"| {name} | {r['year']} | " + " | ".join(cells)
                     + f" | {published(r['venue']).replace('|', '/')} |")
    totals = [str(sum(key in (split(r['capability_axes']) | split(r['conditions'])
                              | split(r['instruments'])) for r in rows)) for key, _ in COLUMNS]
    lines.append(f"| **Total ({len(rows)})** | | " + " | ".join(f"**{t}**" for t in totals) + " | |")
    return lines


def sort_key(r: dict) -> tuple:
    flags = split(r["capability_axes"]) | split(r["instruments"])
    return ("state_verification" not in flags, "grounded" not in flags,
            "multiparty" not in flags, -int(r["year"]), r["title"].lower())


def render() -> str:
    rows = list(csv.DictReader(CSV.open(encoding="utf-8")))
    evaluation = sorted((r for r in rows if r["evidence_role"] == "evaluation"), key=sort_key)
    meta = sorted((r for r in rows if r["evidence_role"] == "meta_evaluation"), key=sort_key)
    out = [
        "# Benchmark map",
        "",
        "<!-- Generated by scripts/build_benchmark_map.py from corpus/voice_agent_corpus.csv. Do not edit. -->",
        "",
        f"Every evaluation work ({len(evaluation)}) and meta-evaluation work ({len(meta)}) in the corpus,",
        "with the capabilities it exercises and the evidence behind its results.",
        "An `x` means the analysed PDF **states** the attribute. A blank means",
        "*not reported*, not *absent*. Works that verify external state come first, then",
        "grounded-outcome and multiparty works.",
        "",
        "**Capability (Axis A):** T timing, R recovery after disruption, G grounded",
        "outcome, M multiparty conduct.  ",
        "**Conditions:** RS real human speech, NE non-English, AV acoustic variation,",
        "LS long or multi-turn session.  ",
        "**Instruments:** S external state or executed-trace verification (matching a",
        "predicted call without executing it is not S), H human reference, J model judge,",
        "Sim simulated interlocutor or environment.",
        "",
        "Something missing or miscoded? Open an issue with the PDF page that supports",
        "the change. Codes follow `corpus/taxonomy_coding.yaml`; definitions are in",
        "`corpus/schema.md`.",
        "",
        "## Evaluation works",
        "",
        *table(evaluation),
        "",
        "## Meta-evaluation works (evaluating the evaluators)",
        "",
        *table(meta),
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("BENCHMARKS.md is stale: run scripts/build_benchmark_map.py", file=sys.stderr)
            return 1
        print("BENCHMARKS.md is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
